package com.electric.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import java.util.HashSet;
import java.util.Set;

/**
 * User - 用户实体类
 * 
 * ═══════════════════════════════════════════════════════════════════════════
 * 一、什么是实体类 (Entity)？
 * ═══════════════════════════════════════════════════════════════════════════
 * 实体类是 Java 对象与数据库表之间的映射桥梁。
 * - Java 对象 → 数据库表的一行记录
 * - Java 类   → 数据库表的结构定义
 * - Java 字段 → 数据库表的列
 * 
 * 使用 JPA (Java Persistence API) 规范，我们可以用注解来定义这种映射关系，
 * 而不需要手写 SQL 语句。
 * 
 * ═══════════════════════════════════════════════════════════════════════════
 * 二、核心注解详解
 * ═══════════════════════════════════════════════════════════════════════════
 * 
 * @Entity
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 标记这个类是一个 JPA 实体，会被 Hibernate 框架管理                        │
 * │ Hibernate 会自动为这个类创建对应的数据库表                                │
 * │ 表名默认为类名（User），可以通过 @Table 自定义                            │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @Table(name = "users")
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 指定数据库表名                                                           │
 * │ 为什么用 "users" 而不是 "user"？                                        │
 * │ - "user" 是 H2、PostgreSQL 等数据库的保留字                              │
 * │ - 使用保留字作为表名会导致 SQL 语法错误                                   │
 * │ - 加 "s" 变成复数形式，既避免冲突又符合命名规范                            │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @Id
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 标记主键字段                                                             │
 * │ 每个实体必须有且仅有一个主键，用于唯一标识每条记录                          │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @GeneratedValue(strategy = GenerationType.IDENTITY)
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 主键生成策略                                                             │
 * │ - IDENTITY: 由数据库自动生成（自增），最常用                              │
 * │ - SEQUENCE: 使用数据库序列（Oracle、PostgreSQL 支持）                     │
 * │ - TABLE:   使用单独的表来生成主键（跨数据库兼容）                          │
 * │ - AUTO:    让 JPA 自动选择合适的策略                                      │
 * │                                                                          │
 * │ 为什么选 IDENTITY？                                                      │
 * │ - H2、MySQL 等数据库支持自增，性能好                                      │
 * │ - 简单易懂，不需要额外的序列对象                                          │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @NotBlank(message = "用户名不能为空")
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ Bean Validation 注解，验证字符串非空且非空白                              │
 * │ - null        → 验证失败                                                 │
 * │ - ""          → 验证失败                                                 │
 * │ - "   "       → 验证失败（只有空格也算空白）                               │
 * │ - "admin"     → 验证通过                                                 │
 * │                                                                          │
 * │ 与 @NotNull 的区别：                                                     │
 * │ - @NotNull: 只检查 null，允许 "" 和 "   "                                │
 * │ - @NotBlank: 检查 null、空字符串和空白字符                                │
 * │                                                                          │
 * │ message 属性：验证失败时的错误消息                                        │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @Size(min = 3, max = 50, message = "用户名长度必须在3-50个字符之间")
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ Bean Validation 注解，验证字符串/集合的长度范围                            │
 * │ - min: 最小长度                                                          │
 * │ - max: 最大长度                                                          │
 * │                                                                          │
 * │ 为什么限制 3-50？                                                        │
 * │ - 太短（<3）：容易被猜测，安全性低                                        │
 * │ - 太长（>50）：数据库存储浪费，显示不便                                   │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @Column(unique = true)
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 定义数据库列的属性                                                       │
 * │ - unique = true: 添加唯一约束，用户名不能重复                              │
 * │ - 其他常用属性：                                                         │
 * │   - nullable = false: 不允许 NULL 值                                     │
 * │   - length = 100: 字符串最大长度                                         │
 * │   - columnDefinition = "TEXT": 自定义列类型                              │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @ManyToMany(fetch = FetchType.EAGER)
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 定义多对多关系                                                           │
 * │ - 一个用户可以有多个角色                                                  │
 * │ - 一个角色可以分配给多个用户                                              │
 * │                                                                          │
 * │ fetch 属性：加载策略                                                     │
 * │ - EAGER（立即加载）: 查询用户时立即加载其所有角色                          │
 * │   优点：使用方便，不会有懒加载异常                                        │
 * │   缺点：可能产生 N+1 查询问题，性能影响                                   │
 * │                                                                          │
 * │ - LAZY（延迟加载）: 只有真正访问角色时才查询                               │
 * │   优点：按需加载，性能好                                                  │
 * │   缺点：需要在事务内访问，否则抛出 LazyInitializationException            │
 * │                                                                          │
 * │ 为什么选 EAGER？                                                         │
 * │ - 用户角色数据量小，立即加载性能影响可忽略                                 │
 * │ - 认证时需要立即知道用户角色，延迟加载反而麻烦                              │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * @JoinTable(...)
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ 定义多对多关系的中间表                                                   │
 * │                                                                          │
 * │ 数据库结构：                                                             │
 * │ ┌─────────────┐     ┌─────────────┐     ┌─────────────┐                │
 * │ │   users     │     │ user_roles  │     │   roles     │                │
 * │ ├─────────────┤     ├─────────────┤     ├─────────────┤                │
 * │ │ id (PK)     │←────│ user_id(FK) │     │ id (PK)     │                │
 * │ │ username    │     │ role_id(FK) │────→│ name        │                │
 * │ │ password    │     └─────────────┘     │ description │                │
 * │ └─────────────┘                         └─────────────┘                │
 * │                                                                          │
 * │ name = "user_roles": 中间表名                                            │
 * │ joinColumns: 当前实体（User）在中间表中的外键列                           │
 * │ inverseJoinColumns: 关联实体（Role）在中间表中的外键列                    │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * ═══════════════════════════════════════════════════════════════════════════
 * 三、为什么使用 Set 而不是 List？
 * ═══════════════════════════════════════════════════════════════════════════
 * 
 * private Set<Role> roles = new HashSet<>();
 * 
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ Set vs List 的选择：                                                     │
 * │                                                                          │
 * │ Set（集合）：                                                            │
 * │ - 不允许重复元素                                                         │
 * │ - 无顺序                                                                 │
 * │ - 使用 HashSet 实现，查找效率 O(1)                                       │
 * │ - 适合：角色、权限等不允许重复的场景                                      │
 * │                                                                          │
 * │ List（列表）：                                                           │
 * │ - 允许重复元素                                                           │
 * │ - 有顺序                                                                 │
 * │ - 使用 ArrayList 实现，查找效率 O(n)                                     │
 * │ - 适合：评论、订单项等有序且可能重复的场景                                 │
 * │                                                                          │
 * │ 为什么角色用 Set？                                                       │
 * │ - 一个用户不应该有重复的角色                                              │
 * │ - 角色顺序没有意义                                                       │
 * │ - 查找效率更高                                                           │
 * └─────────────────────────────────────────────────────────────────────────┘
 * 
 * ═══════════════════════════════════════════════════════════════════════════
 * 四、安全最佳实践
 * ═══════════════════════════════════════════════════════════════════════════
 * 
 * 密码存储：
 * ┌─────────────────────────────────────────────────────────────────────────┐
 * │ ❌ 错误做法：明文存储密码                                                │
 * │    password = "123456"                                                  │
 * │                                                                          │
 * │ ✅ 正确做法：使用 BCrypt 加密存储                                         │
 * │    password = "$2a$10$N9qo8uLOickgx2..."                                │
 * │                                                                          │
 * │ BCrypt 特点：                                                            │
 * │ - 单向加密，不可逆                                                       │
 * │ - 每次加密结果不同（包含随机盐值）                                        │
 * │ - 相同密码的加密结果不同，防止彩虹表攻击                                  │
 * │ - 计算成本可调，抵抗暴力破解                                              │
 * └─────────────────────────────────────────────────────────────────────────┘
 */
@Entity
@Table(name = "users")
public class User {
    
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @NotBlank(message = "用户名不能为空")
    @Size(min = 3, max = 50, message = "用户名长度必须在3-50个字符之间")
    @Column(unique = true)
    private String username;

    @NotBlank(message = "密码不能为空")
    private String password;

    @ManyToMany(fetch = FetchType.EAGER)
    @JoinTable(
        name = "user_roles",
        joinColumns = @JoinColumn(name = "user_id"),
        inverseJoinColumns = @JoinColumn(name = "role_id")
    )
    private Set<Role> roles = new HashSet<>();

    private Boolean enabled = true;

    public User() {}

    public User(String username, String password) {
        this.username = username;
        this.password = password;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public Set<Role> getRoles() {
        return roles;
    }

    public void setRoles(Set<Role> roles) {
        this.roles = roles;
    }

    public Boolean getEnabled() {
        return enabled;
    }

    public void setEnabled(Boolean enabled) {
        this.enabled = enabled;
    }
}
